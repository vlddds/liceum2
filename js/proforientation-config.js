/* Профтест: які профілі радити і які гуртки

   Самі профілі (назви, описи, предмети НМТ) - в clusters.js, тут тільки до яких типів Голланда вони підходять.
   types: "R" практичний, "I" дослідницький, "A" творчий, "S" соціальний, "E" підприємливий, "C" систематичний.
   Можна 1-3 літери. Тест бере середній бал по цих типах і радить профіль з найбільшим.
   Новий профіль у clusters.js - дописати і сюди, інакше профтест його не радитиме.

   Гуртки для "Що далі": clubsByType - які гуртки радити під кожен тип.
   Назви мають бути точно як у data.js (там, де гуртки), якщо такого нема - він просто не покажеться. */
window.PROF_CONFIG = (function () {
  var TYPES = {
    IT: ["I", "C"], ENG: ["I", "R"], BIO: ["I", "S"],
    FL: ["S", "A"], UA: ["A", "S"],
    HIST: ["S", "E"], ECO: ["E", "C"]
  };
  var C = window.CLUSTERS || { profiles: {} };
  return {
    /* якщо другий профіль відстає менше ніж на стільки балів, показуємо його як "також може підійти" */
    closeGap: 3,

    profiles: Object.keys(TYPES).filter(function (id) { return C.profiles[id]; }).map(function (id) {
      var p = C.profiles[id];
      return { id: id, name: p.name, types: TYPES[id], subjects: p.nmt, description: p.desc };
    }),

    clubsByType: {
      R: ["Робототехніка", "Юні екологи"],
      I: ["Робототехніка", "Юні екологи", "Шаховий клуб"],
      A: ["Образотворче мистецтво", "Вокальний гурток", "Dnipro Dance"],
      S: ["Волейбол", "Футбол", "Вокальний гурток"],
      E: ["Шаховий клуб", "Волейбол"],
      C: ["Шаховий клуб", "Робототехніка"]
    }
  };
})();
